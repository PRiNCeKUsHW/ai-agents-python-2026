"""Real (recorded) sound effects for the lesson videos.

The original modules use effects synthesized by tools/make_audio_assets.py. From Module 6 on, the
builder uses recorded effects from shared/sfx/, which this tool fills from three sources:

  python tools/sfx.py setup                      # the 21 recorded effects bundled with Claude's
                                                 # media-use skill (Pixabay Content License)
  python tools/sfx.py openverse "soft whoosh" --name whoosh
                                                 # search openverse.org (CC0 / CC BY only) and download
  python tools/sfx.py add ~/Downloads/x.wav --name pop --source Earshot \
      --license "Earshot licence" --credit "Pop by ... (earshot)"
                                                 # a file you downloaded yourself (Earshot or anywhere)
  python tools/sfx.py list

Every effect is converted to 24 kHz mono WAV, silence-trimmed and peak-normalised to -3 dBFS, so
the builder's gains mean the same thing for every source. shared/sfx/sfx.json records where each
file came from and its licence; CREDITS.md is regenerated from it. The audio files themselves are
not committed (their licences allow use in videos, not re-hosting the raw files): run `setup`
(and any `openverse` commands, which are replayed from the URLs in sfx.json) on a new machine.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import urllib.parse
import urllib.request
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "shared/sfx"
MANIFEST = OUT / "sfx.json"
SR = 24000
PEAK = 10 ** (-3 / 20)
BUNDLE = Path(os.environ.get("SFX_BUNDLE", Path.home() / ".claude/skills/media-use/audio/assets/sfx"))
OPENVERSE = "https://api.openverse.org/v1/audio/"
PIXABAY = ("Pixabay Content License (pixabay.com/service/license-summary): free for commercial "
           "and non-commercial use, no attribution required")


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}


def save_manifest(data: dict) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps(dict(sorted(data.items())), indent=2) + "\n")
    lines = ["# Sound effect credits", "",
             "Recorded sound effects used in the lesson videos from Module 6 on. "
             "Generated by `python tools/sfx.py`; the audio files are not committed.", "",
             "| Effect | Source | Licence | Credit |", "|---|---|---|---|"]
    for name, e in sorted(data.items()):
        lines.append(f"| `{name}` | {e['source']} | {e['license']} | {e.get('credit') or '-'} |")
    (OUT / "CREDITS.md").write_text("\n".join(lines) + "\n")


def convert(src: Path, name: str) -> float:
    """Any audio file -> shared/sfx/<name>.wav (24 kHz mono, trimmed, -3 dBFS peak)."""
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "x.wav"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(src), "-ac", "1", "-ar", str(SR),
                        "-c:a", "pcm_f32le", str(wav)], check=True)
        x, _ = sf.read(wav, dtype="float32")
    loud = np.flatnonzero(np.abs(x) > 10 ** (-50 / 20))
    if not len(loud):
        raise SystemExit(f"{src}: silent file")
    start = max(0, loud[0] - int(0.005 * SR))
    end = min(len(x), loud[-1] + int(0.02 * SR))
    x = x[start:end]
    fade = min(len(x), int(0.01 * SR))
    x[-fade:] *= np.linspace(1, 0, fade)
    x = x / np.abs(x).max() * PEAK
    sf.write(OUT / f"{name}.wav", x, SR, subtype="PCM_16")
    return round(len(x) / SR, 3)


def setup(_: argparse.Namespace) -> None:
    if not (BUNDLE / "manifest.json").exists():
        raise SystemExit(f"bundled effects not found at {BUNDLE} (set SFX_BUNDLE)")
    bundle = json.loads((BUNDLE / "manifest.json").read_text())
    data = load_manifest()
    for name, meta in bundle.items():
        seconds = convert(BUNDLE / meta["file"], name)
        data[name] = {"file": f"{name}.wav", "seconds": seconds, "source": "Pixabay, via Claude media-use skill",
                      "license": PIXABAY, "credit": None, "use": meta["description"]}
        print(f"{name:<18} {seconds:5.2f} s")
    for name, e in data.items():                 # replay Openverse downloads recorded earlier
        if e.get("url") and not (OUT / e["file"]).exists():
            fetch(e["url"], name)
    save_manifest(data)
    print(f"{len(bundle)} recorded effects in {OUT.relative_to(ROOT)}")


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "ai-agents-course-sfx/1.0"})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.read()
    except OSError as exc:
        host = urllib.parse.urlparse(url).hostname
        raise SystemExit(f"could not reach {host} ({exc}). If you are in a cloud session, add "
                         f"{host} to the environment's allowed network domains.") from None


def fetch(url: str, name: str) -> float:
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / Path(urllib.parse.urlparse(url).path).name
        src.write_bytes(get(url))
        return convert(src, name)


def openverse(args: argparse.Namespace) -> None:
    query = urllib.parse.urlencode({"q": args.query, "license": "cc0,by", "page_size": 20})
    results = json.loads(get(f"{OPENVERSE}?{query}"))["results"]
    fits = [r for r in results if r.get("license") in ("cc0", "by") and r.get("url")
            and (r.get("duration") or 0) <= args.max_seconds * 1000]
    if not fits:
        raise SystemExit(f"no CC0 / CC BY result under {args.max_seconds} s for {args.query!r}")
    for i, r in enumerate(fits[:8]):
        print(f"{i}: {r['title']!r} by {r.get('creator')} ({r['license']}, "
              f"{(r.get('duration') or 0) / 1000:.1f} s) {r.get('foreign_landing_url')}")
    pick = fits[args.pick]
    seconds = fetch(pick["url"], args.name)
    data = load_manifest()
    lic = "CC0" if pick["license"] == "cc0" else f"CC BY {pick.get('license_version', '')}".strip()
    data[args.name] = {"file": f"{args.name}.wav", "seconds": seconds, "source": "Openverse",
                       "license": lic, "url": pick["url"],
                       "credit": f"\"{pick['title']}\" by {pick.get('creator')} ({lic}), "
                                 f"{pick.get('foreign_landing_url')}",
                       "use": args.query}
    save_manifest(data)
    print(f"saved {args.name}: {seconds} s, {lic}")


def add(args: argparse.Namespace) -> None:
    seconds = convert(Path(args.file), args.name)
    data = load_manifest()
    data[args.name] = {"file": f"{args.name}.wav", "seconds": seconds, "source": args.source,
                       "license": args.license, "credit": args.credit, "use": args.use or ""}
    save_manifest(data)
    print(f"saved {args.name}: {seconds} s from {args.source}")


def list_(_: argparse.Namespace) -> None:
    data = load_manifest()
    for name, e in data.items():
        ok = "ok " if (OUT / e["file"]).exists() else "MISSING"
        print(f"{ok} {name:<18} {e['seconds']:5.2f} s  {e['source']}")
    if not data:
        print("no recorded effects yet: python tools/sfx.py setup")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("setup").set_defaults(fn=setup)
    o = sub.add_parser("openverse")
    o.add_argument("query")
    o.add_argument("--name", required=True)
    o.add_argument("--pick", type=int, default=0, help="which listed result to keep")
    o.add_argument("--max-seconds", type=float, default=6)
    o.set_defaults(fn=openverse)
    a = sub.add_parser("add")
    a.add_argument("file")
    a.add_argument("--name", required=True)
    a.add_argument("--source", required=True, help="e.g. Earshot")
    a.add_argument("--license", required=True)
    a.add_argument("--credit", default=None)
    a.add_argument("--use", default=None)
    a.set_defaults(fn=add)
    sub.add_parser("list").set_defaults(fn=list_)
    args = p.parse_args()
    if not shutil.which("ffmpeg"):
        sys.exit("ffmpeg is required")
    args.fn(args)


if __name__ == "__main__":
    main()
